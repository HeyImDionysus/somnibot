-- V31 PR #43: Gathering, Crafting, Farming
-- ==============================================
-- New guild_config columns for gathering/crafting/farming settings.
-- New tables: economy_loot_tables, economy_recipes, economy_crops, economy_farm_plots.
--
-- IMPORTANT: This is the FAKE economy. No connection to real-money commerce.

-- ── guild_config additions ──────────────────────────────────

ALTER TABLE guild_config
  ADD COLUMN IF NOT EXISTS economy_gathering_enabled           boolean   NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS economy_gathering_cooldown_seconds  integer   NOT NULL DEFAULT 300,
  ADD COLUMN IF NOT EXISTS economy_crafting_enabled            boolean   NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS economy_crafting_cooldown_seconds   integer   NOT NULL DEFAULT 60,
  ADD COLUMN IF NOT EXISTS economy_farming_enabled             boolean   NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS economy_farm_grid_size              integer   NOT NULL DEFAULT 9,
  ADD COLUMN IF NOT EXISTS economy_farming_wilt_enabled        boolean   NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS economy_fertilizer_time_reduction_pct integer NOT NULL DEFAULT 50;

-- ── economy_loot_tables ─────────────────────────────────────
-- Defines drop tables for gathering commands (/hunt, /dig, /mine).
-- source_type: 'hunt' | 'dig' | 'mine'
-- tool_tier: minimum tool tier required (0 = bare hands, 1 = basic, 2 = improved, 3 = master)

CREATE TABLE IF NOT EXISTS economy_loot_tables (
  id            uuid    PRIMARY KEY DEFAULT gen_random_uuid(),
  guild_id      text    NOT NULL,
  source_type   text    NOT NULL CHECK (source_type IN ('hunt', 'dig', 'mine')),
  item_name     text    NOT NULL,
  emoji         text    NOT NULL DEFAULT '📦',
  rarity        text    NOT NULL DEFAULT 'common' CHECK (rarity IN ('common', 'uncommon', 'rare', 'epic', 'legendary')),
  min_qty       integer NOT NULL DEFAULT 1,
  max_qty       integer NOT NULL DEFAULT 1,
  weight        integer NOT NULL DEFAULT 100,   -- higher weight = more likely
  tool_tier     integer NOT NULL DEFAULT 0,
  sell_value    bigint  NOT NULL DEFAULT 10,     -- base sell price per unit
  gives_item_id uuid    REFERENCES economy_items(id) ON DELETE SET NULL, -- links to shop item if applicable
  active        boolean NOT NULL DEFAULT true,
  created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_economy_loot_guild_source
  ON economy_loot_tables (guild_id, source_type) WHERE active = true;

-- ── Default loot entries (applied per-guild on first enable via bot logic) ──
